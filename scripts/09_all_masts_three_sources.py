#!/usr/bin/env python3
"""All five masts, three sources side by side: UAV, terrestrial laser, and synthetic.

Produces a 3 x 5 panel figure -- one column per mast (bow -> stern), one row per
source -- so the three data sources this study relies on can be compared at a glance:

    row 1  UAV photogrammetry   the measurement
    row 2  terrestrial laser    the independent cross-check
    row 3  matched synthetic    the phantom the accuracy figure is derived on

Two things the figure is meant to make obvious, both of which matter for how far the
results can be trusted:

  * the laser's coverage is very uneven -- dense on some masts, and on the Foremast
    so sparse (~1.9k points) that it cannot be fitted at all. The Foremast carries the
    largest UAV bend, so the largest signal in the study is the one the second sensor
    cannot confirm. That panel is still drawn, as a broken one-sided scatter of returns
    flagged in red; it is excluded from every fit and from the cross-validation.
  * the synthetic row is generated by ``matched_phantom`` with ``phantom_geometry``,
    i.e. calibrated to the *measured* per-slice statistics **and** to each mast's own
    height, radius, taper and point density -- so the Jiggermast phantom is short and
    the Mizzenmast phantom is barely tapered, exactly as the real ones are. Matching
    the noise but not the geometry would leave five identical generic tubes, and the
    resemblance to row 1 is precisely what licenses transferring an accuracy figure.

Modes
-----
--mode cloud     (default) point clouds, coloured by height
--mode profile   recovered bending profiles for the same three sources

Usage
-----
    python scripts/09_all_masts_three_sources.py
    python scripts/09_all_masts_three_sources.py --mode profile
"""
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from _common import base_parser, ensure_dirs, label_of, load_drone, load_laser
from mastfit.io import coregister, robust_clean
from mastfit.pipeline import fit_mast
from mastfit.validate import matched_phantom, phantom_geometry

MIN_LASER_POINTS = 2000
ROWS = ["UAV photogrammetry", "Terrestrial laser", "Synthetic (matched)"]


def _thin(P, target=4000):
    step = max(1, len(P) // target)
    return P[::step]


def _upright(P):
    """Rotate a mast so that its own fitted axis is vertical, then centre it.

    Why rotate rather than merely translate
    ---------------------------------------
    The two scans are georeferenced independently, and the laser cloud carries a
    global tilt (levelling/registration) of the same order as the ~1.5 deg design
    rake itself: in the common ship frame the UAV has the masts raking *aft*
    (physically correct) while the laser has them raking *forward*. Both cannot be
    true of the same ship, so absolute mast lean is **not comparable between the two
    sensors**, and drawing them in a shared world frame would show a difference that
    is an artefact of levelling, not of the structure.

    Crucially this does not touch the results: bending is measured as departure from
    each mast's *own* straight axis, so any rigid tilt cancels exactly. That is
    precisely the payoff of a self-referential estimand, and it is why the
    Bland-Altman bending agreement stands even though the frames disagree on rake.

    This figure is about shape, coverage and density, so each mast is shown upright in
    its own axis frame. Rake is reported in Table 1 from the UAV data alone.
    """
    from mastfit.geometry import irls_axis, orthonormal_basis, pca_axis

    P = np.asarray(P, dtype=float)
    c0, d0, _ = pca_axis(P)
    c, d = irls_axis(P, c0, d0)
    B, d = orthonormal_basis(d)          # B rows span the plane perpendicular to d
    R = np.vstack([B[0], B[1], d])       # rows: local x, y, axis -> maps axis to +z
    Q = (P - c) @ R.T
    Q[:, 2] -= Q[:, 2].min()
    Q[:, 0] -= np.median(Q[:, 0])
    Q[:, 1] -= np.median(Q[:, 1])
    return Q


def figure_clouds(drone, laser, args, laser_counts):
    fig = plt.figure(figsize=(16.5, 11))
    zmax = max(P[:, 2].max() - P[:, 2].min() for P in drone) + 3

    for col in range(5):
        # The sparse laser mast is DRAWN, not blanked out: the reader should see *why*
        # it cannot be fitted (a broken, one-sided scatter of ~1.9k returns) rather than
        # be told so in a text box. It is flagged, and excluded from every fit.
        too_sparse = laser_counts[col] < MIN_LASER_POINTS
        sources = [
            _upright(drone[col]),
            _upright(laser[col]),
            _upright(matched_phantom(seed=col, correlated=True, **phantom_geometry(col))[0]),
        ]
        for row, P in enumerate(sources):
            ax = fig.add_subplot(3, 5, row * 5 + col + 1, projection="3d")
            if False:
                pass
            else:
                S = _thin(P)
                ax.scatter(S[:, 0], S[:, 1], S[:, 2], c=S[:, 2], cmap="turbo",
                           s=0.7, alpha=.6, vmin=0, vmax=zmax)
                ax.view_init(elev=8, azim=-72)
                ax.set_xlim(-1.6, 1.6)
                ax.set_ylim(-1.6, 1.6)
                ax.set_zlim(0, zmax)
                ax.set_xticks([])
                ax.set_yticks([])
                ax.set_zticks([0, int(zmax // 2), int(zmax)] if col == 0 else [])
                ax.grid(False)
                for pane in (ax.xaxis, ax.yaxis, ax.zaxis):
                    pane.pane.set_facecolor((1, 1, 1, 0))
                    pane.pane.set_edgecolor((0.85, 0.85, 0.85, 0.4))
                try:
                    ax.set_box_aspect((1, 1, 4))
                except Exception:
                    pass
                if row == 1:
                    colour = "#c0392b" if too_sparse else "#555"
                    ax.text2D(0.5, 0.02, f"{laser_counts[col]:,} pts", transform=ax.transAxes,
                              ha="center", fontsize=7.5,
                              color=colour, fontweight="bold" if too_sparse else "normal")
                    if too_sparse:
                        ax.text2D(0.5, 0.90, "too sparse to fit\nexcluded from cross-validation",
                                  transform=ax.transAxes, ha="center", va="top",
                                  fontsize=7.5, color="#c0392b", fontweight="bold")
                else:
                    ax.text2D(0.5, 0.02, f"{len(P):,} pts", transform=ax.transAxes,
                              ha="center", fontsize=7, color="#555")
            if row == 0:
                ax.set_title(label_of(col), fontsize=11, pad=0)
            if col == 0:
                ax.text2D(-0.18, 0.5, ROWS[row], transform=ax.transAxes, rotation=90,
                          va="center", ha="center", fontsize=11, fontweight="bold")

    fig.suptitle("Five masts, three sources: UAV photogrammetry, terrestrial laser, and the "
                 "statistically-matched synthetic phantom\n(bow \u2192 stern; colour = height; "
                 "each mast drawn upright in its own axis frame, so shape and coverage are directly comparable)",
                 fontsize=12)
    fig.subplots_adjust(left=0.045, right=0.99, top=0.93, bottom=0.02,
                        wspace=0.02, hspace=0.06)
    out = os.path.join(args.outdir, "fig_all_masts_three_sources.png")
    fig.savefig(out, dpi=115)
    plt.close(fig)
    return out


def figure_profiles(drone, laser, args, laser_counts):
    fig, axs = plt.subplots(1, 5, figsize=(16, 5.2), sharey=True)
    colours = {"UAV": "#2f6690", "Laser": "#c0392b", "Synthetic": "#2e8b57"}

    for col in range(5):
        ax = axs[col]
        rd = fit_mast(drone[col], n_slices=args.slices, bandwidth_m=args.bandwidth)
        ax.plot(rd.bend_total_mm, rd.height, color=colours["UAV"], lw=2.1,
                label=f"UAV ({rd.max_bend_mm:.0f} mm)")

        if laser_counts[col] >= MIN_LASER_POINTS:
            rl = fit_mast(robust_clean(laser[col]), n_slices=args.slices,
                          bandwidth_m=args.bandwidth)
            ax.plot(rl.bend_total_mm, rl.height, color=colours["Laser"], lw=2.1,
                    label=f"Laser ({rl.max_bend_mm:.0f} mm)")
        else:
            ax.plot([], [], color=colours["Laser"], lw=2.1, label="Laser: too sparse")

        rs = fit_mast(matched_phantom(seed=col, correlated=True, **phantom_geometry(col))[0],
                      n_slices=args.slices, bandwidth_m=args.bandwidth)
        ax.plot(rs.bend_total_mm, rs.height, color=colours["Synthetic"], lw=1.6,
                ls="--", alpha=.85, label=f"Synthetic ({rs.max_bend_mm:.0f} mm)")

        ax.axvspan(0, 37, color="#bbb", alpha=.30, zorder=0)
        ax.set_title(label_of(col), fontsize=11)
        ax.set_xlabel("total bend [mm]")
        ax.grid(alpha=.25)
        ax.legend(fontsize=7.5, loc="upper right")
    axs[0].set_ylabel("height above base [m]")
    fig.suptitle("Recovered bending profiles by source. Shaded band = the ~30\u201340 mm "
                 "correlated-error floor: bends inside it are not resolved.", fontsize=11.5)
    fig.tight_layout()
    out = os.path.join(args.outdir, "fig_all_masts_profiles.png")
    fig.savefig(out, dpi=115)
    plt.close(fig)
    return out


def main():
    p = base_parser(__doc__)
    p.add_argument("--mode", choices=["cloud", "profile"], default="cloud",
                   help="point clouds (default) or recovered bending profiles")
    args = p.parse_args()
    ensure_dirs(args.outdir)

    drone_raw = load_drone(args)
    laser_raw = load_laser(args)

    # The two scans are georeferenced independently: their frames differ by a yaw
    # rotation and a handedness flip. Without co-registration a mast would appear to
    # lean in a different direction in the laser row than in the UAV row -- a pure
    # frame artefact that would be read as a real disagreement. Co-register first so
    # that orientation is directly comparable across rows.
    drone, laser = coregister(drone_raw, laser_raw)
    # keep the raw laser clouds for the point counts / sparsity check
    laser = [lz if len(lr) >= MIN_LASER_POINTS else lr
             for lz, lr in zip(laser, laser_raw)]
    laser_counts = [len(P) for P in laser_raw]

    out = (figure_clouds if args.mode == "cloud" else figure_profiles)(
        drone, laser, args, laser_counts)
    print(f"wrote {out}")

    sparse = [label_of(i) for i in range(5) if laser_counts[i] < MIN_LASER_POINTS]
    if sparse:
        print(f"NOTE: laser coverage too sparse to fit: {', '.join(sparse)}")
        print("      This is why the largest UAV bend cannot be independently confirmed.")


if __name__ == "__main__":
    main()
